#!/usr/bin/env python3
"""Experimental prepacked group-64 INT4 QK with BF16 PV and FP32 softmax.

Derived from the INT8/transposed generators and H3's signed INT4 operand schema
in attention_i4qks_family.loom, revision 95ed12f43bd3e596cbfad175c22de9560447e9e5
(Apache-2.0). The existing benchmark ABI is retained: 36 words/head, with 16
INT4 payload words, 16 zero words, two FP32 group scales and two zero words.
Only operator experiments: no model/default selector change or quality claim.
"""
import argparse
import re
from pathlib import Path
from omni_attention_int8_candidate import generate_prepacked


def replace_once(source, old, new):
    assert source.count(old) == 1, old
    return source.replace(old, new)


def generate_packing(source):
    # Four values per lane; adjacent lanes join eight nibbles into one word.
    # The optional H128 transform remains intact; scaling groups follow it.
    source = source.replace('INT8 Q/K packing', 'INT4 group-64 Q/K packing')
    source = source.replace('Each head stores 32 packed words, one FP32 scale and three zero padding words.',
                            'Each head stores 16 packed words, 16 zeros, two FP32 scales and two zeros.')
    for old, new in [('127.0', '7.0'), ('-127.0', '-7.0'),
                     ('%mask = vector.constant 255', '%mask = vector.constant 15')]:
        source = source.replace(old, new)
    old = ' %row_max = kernel.subgroup.reduce<maxnumf> %local_max : f32'
    lines = [' %i4_wave_width = scalar.constant 32 : i32']
    previous = '%local_max'
    for delta in [1, 2, 4, 8]:
        lines += [f' %i4_delta{delta} = scalar.constant {delta} : i32',
                  f' %i4_other{delta}, %i4_valid{delta} = kernel.subgroup.shuffle<xor> {previous}, %i4_delta{delta}, %i4_wave_width : f32, i32, i32',
                  f' %i4_max{delta} = scalar.maxnumf {previous}, %i4_other{delta} : f32']
        previous = f'%i4_max{delta}'
    lines += [' %row_max = scalar.maxnumf %i4_max8, %tiny : f32']
    source = replace_once(source, old, '\n'.join(lines))
    for name, amount in [('s8',4),('s16',8),('s24',12)]:
        old = f' %{name} = scalar.constant {int(name[1:])} : i32'
        source = replace_once(source, old, f' %{name} = scalar.constant {amount} : i32')
    start = source.index(' %base = index.mul %head, %c36 : index')
    end = source.index(' kernel.return', start)
    source = source[:start] + ''' %i4_partner, %i4_partner_valid = kernel.subgroup.shuffle<xor> %word, %i4_delta1, %i4_wave_width : i32, i32, i32
 %i4_shift16 = scalar.constant 16 : i32
 %i4_upper = scalar.shli %i4_partner, %i4_shift16 : i32
 %i4_word = scalar.ori %word, %i4_upper : i32
 %i4_two = index.constant 2 : index
 %i4_sixteen = index.constant 16 : index
 %i4_thirtyfour = index.constant 34 : index
 %i4_zero = scalar.constant 0 : i32
 %base = index.mul %head, %c36 : index
 %i4_parity = index.rem %lane, %i4_two : index
 %i4_even = index.cmp eq, %i4_parity, %c0 : index
 scf.if %i4_even {
  %i4_word_index = index.div %lane, %i4_two : index
  %i4_out0 = index.add %base, %i4_word_index : index
  %i4_out = index.assume %i4_out0 [lt(%i4_out0, %out_width)] : index
  view.store %i4_word, %ov[%row, %i4_out] : i32, view<[%count]x[%out_width]xi32>
 }
 %i4_low_half = index.cmp ult, %lane, %i4_sixteen : index
 scf.if %i4_low_half {
  %i4_pad_local = index.add %lane, %i4_sixteen : index
  %i4_pad0 = index.add %base, %i4_pad_local : index
  %i4_pad = index.assume %i4_pad0 [lt(%i4_pad0, %out_width)] : index
  view.store %i4_zero, %ov[%row, %i4_pad] : i32, view<[%count]x[%out_width]xi32>
 }
 %i4_group_lane = index.rem %lane, %i4_sixteen : index
 %i4_group_first = index.cmp eq, %i4_group_lane, %c0 : index
 scf.if %i4_group_first {
  %i4_group = index.div %lane, %i4_sixteen : index
  %i4_scale_local = index.add %c32, %i4_group : index
  %i4_scale0 = index.add %base, %i4_scale_local : index
  %i4_scale = index.assume %i4_scale0 [lt(%i4_scale0, %out_width)] : index
  view.store %scale, %sv[%row, %i4_scale] : f32, view<[%count]x[%out_width]xf32>
 }
 %i4_pad_last = index.cmp ult, %lane, %i4_two : index
 scf.if %i4_pad_last {
  %i4_last_local = index.add %lane, %i4_thirtyfour : index
  %i4_last0 = index.add %base, %i4_last_local : index
  %i4_last = index.assume %i4_last0 [lt(%i4_last0, %out_width)] : index
  view.store %i4_zero, %ov[%row, %i4_last] : i32, view<[%count]x[%out_width]xi32>
 }
''' + source[end:]
    return ('// Experimental INT4 group-64 packing; generated by omni_attention_int4_candidate.py.\n'
            '// Legacy INT8 export/config names retain the 36-word benchmark ABI.\n'
            '// Layout: 16 INT4 words, 16 zeros, two group scales, two zeros.\n' + source)


def generate(queries=128, keys=32):
    s = generate_prepacked(queries, keys)
    # Global stride stays 36; shrink only the LDS payload rows and fragments.
    s = s.replace('element_format=i8, payload_elements=16, payload_registers=4',
                  'element_format=i4, payload_elements=16, payload_registers=2')
    # Probability/output BF16 interleaving also uses four-word vectors. Only
    # Q/K integer operands shrink; changing those BF16 bitcasts is invalid.
    s = '\n'.join(line.replace('vector<4xi32>', 'vector<2xi32>')
                  if re.match(r'^(?:%q[pf]\d|%k[qdf]\d|%dot\d|vector.store %kq\d)', line)
                  else line for line in s.split('\n'))
    s = s.replace(f'view<{keys}x36xi32>', f'view<{keys}x20xi32>')
    old_offset = keys * 36 * 4 + 128 * (keys + 8) * 2
    offset = keys * 20 * 4 + 128 * (keys + 8) * 2
    for old, new in [(f'%voffset = index.constant {keys*36*4}', f'%voffset = index.constant {keys*20*4}'),
                     (f'%lds_bytes = index.constant {old_offset+keys*4}', f'%lds_bytes = index.constant {offset+keys*8}'),
                     (f'%k_scale_offset = index.constant {old_offset}', f'%k_scale_offset = index.constant {offset}')]:
        s = replace_once(s, old, new)
    s = replace_once(s, f'%k_scales = buffer.view %lds[%k_scale_offset] : buffer -> view<{keys}xf32>',
        f'''%k_scales = buffer.view %lds[%k_scale_offset] : buffer -> view<{keys}xf32>
%k_scale_hi_offset = index.constant {offset+keys*4} : offset
%k_scales_hi = buffer.view %lds[%k_scale_hi_offset] : buffer -> view<{keys}xf32>''')
    for axis in ['q','k']:
        s = replace_once(s, f'%{axis}word_limit = index.sub %{axis}words, %c4 : index',
                         f'%{axis}word_limit = index.sub %{axis}words, %c2 : index')
    for i in range(8):
        s = replace_once(s, f'%qwcol{i}raw = index.add %qword_base, %c{i*4} : index',
                         f'%qwcol{i}raw = index.add %qword_base, %c{i*2} : index')
        s = s.replace(f'multiple_of(%qwcol{i}raw, 4)', f'multiple_of(%qwcol{i}raw, 2)')
    qscale = '%q_score_scale = scalar.mulf %qscale, %scale : f32'
    s = replace_once(s, qscale, qscale + '''
%qscolhiraw = index.add %qscolraw, %c1 : index
%qscolhi = index.assume %qscolhiraw [lt(%qscolhiraw, %qwords)] : index
%qscale_hi = view.load %qscaleview[%qread, %qscolhi] : view<[%queries]x[%qwords]xf32> -> f32
%q_score_scale_hi = scalar.mulf %qscale_hi, %scale : f32''')
    for packet in range((keys*8+queries*2-1)//(queries*2)):
        s = replace_once(s, f'%kq{packet}_col = index.mul %ktc{packet}, %c4 : index',
                         f'%kq{packet}_col = index.mul %ktc{packet}, %c2 : index')
        s = s.replace(f'multiple_of(%kwcol{packet}raw, 4)', f'multiple_of(%kwcol{packet}raw, 2)')
        store = f'view.store %kscale{packet}, %k_scales[%kr{packet}] : f32, view<{keys}xf32>'
        s = replace_once(s, store, store + f'''
 %kscolhi{packet}raw = index.add %kscol{packet}raw, %c1 : index
 %kscolhi{packet} = index.assume %kscolhi{packet}raw [lt(%kscolhi{packet}raw, %kwords)] : index
 %kscalehi{packet} = view.load %kscaleview[%kread{packet}, %kscolhi{packet}] : view<[%keys]x[%kwords]xf32> -> f32
 view.store %kscalehi{packet}, %k_scales_hi[%kr{packet}] : f32, view<{keys}xf32>''')
    for part in range(keys//16):
        for dim in range(8):
            s = replace_once(s, f'%kd{part}_{dim} = vector.load %ks[%krow{part}, %c{dim*4}]',
                             f'%kd{part}_{dim} = vector.load %ks[%krow{part}, %c{dim*2}]')
        s = replace_once(s, f'%dot{part}_4 = vector.mma %kf{part}_4, %qf4, %dot{part}_3',
                         f'%dot{part}_4 = vector.mma %kf{part}_4, %qf4, %initi')
        old = f'%scaled{part} = vector.sitofp %dot{part}_7 : vector<8xi32> to vector<8xf32>'
        s = replace_once(s, old, old + f'\n%scaledlo{part} = vector.sitofp %dot{part}_3 : vector<8xi32> to vector<8xf32>')
        for element in range(8):
            old = f'''%dot_value{part}_{element} = vector.extract %scaled{part}[{element}] : vector<8xf32> -> f32
%q_scaled{part}_{element} = scalar.mulf %dot_value{part}_{element}, %q_score_scale : f32
%value{part}_{element} = scalar.mulf %q_scaled{part}_{element}, %ks_value{part}_{element} : f32'''
            new = f'''%ks_hi{part}_{element} = view.load %k_scales_hi[%ks_local{part}_{element}] : view<{keys}xf32> -> f32
%dot_lo{part}_{element} = vector.extract %scaledlo{part}[{element}] : vector<8xf32> -> f32
%dot_hi{part}_{element} = vector.extract %scaled{part}[{element}] : vector<8xf32> -> f32
%q_lo{part}_{element} = scalar.mulf %dot_lo{part}_{element}, %q_score_scale : f32
%q_hi{part}_{element} = scalar.mulf %dot_hi{part}_{element}, %q_score_scale_hi : f32
%score_lo{part}_{element} = scalar.mulf %q_lo{part}_{element}, %ks_value{part}_{element} : f32
%score_hi{part}_{element} = scalar.mulf %q_hi{part}_{element}, %ks_hi{part}_{element} : f32
%value{part}_{element} = scalar.addf %score_lo{part}_{element}, %score_hi{part}_{element} : f32'''
            s = replace_once(s, old, new)
    return '// Experimental group-64 INT4 QK; BF16 PV. No model qualification.\n' + s


if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('output', type=Path)
    p.add_argument('--queries', type=int, choices=(64,128,256), default=128)
    p.add_argument('--keys', type=int, choices=(32,64), default=32)
    p.add_argument('--packing-source', type=Path)
    p.add_argument('--packing-output', type=Path)
    a = p.parse_args()
    if bool(a.packing_source) != bool(a.packing_output):
        p.error('--packing-source and --packing-output must be supplied together')
    a.output.write_text(generate(a.queries,a.keys))
    if a.packing_output:
        a.packing_output.write_text(generate_packing(a.packing_source.read_text()))
